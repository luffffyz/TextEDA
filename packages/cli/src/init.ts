// `texteda init`: scaffold an empty project.
//
// Contract per AGENTS.md "init contract (settled)":
//   - create only `project.toml`, `assets/`, `design/`, `external/`, `docs/`, `docs/README.md` (ADR-0031);
//   - put `.gitkeep` in the empty directories to keep them;
//   - `project.toml` has only three required entries: `name` / `version` / `format`;
//   - no network access, no template fetching, no `dist/`;
//   - deterministic output: the same name yields byte-identical files.
//
// This module only computes "which files to write and what their contents are" and never touches the file system — disk writes live in `scripts/texteda.ts`.
// That way the contract itself can be unit-tested without spinning up temp directories.

import { formatVersion, SUPPORTED_LANGUAGE } from "@texteda/parser";

/** The tool's current language version; `project.toml`'s `format` takes it. */
export const CURRENT_FORMAT = formatVersion(SUPPORTED_LANGUAGE);

/** Default version for a new project. */
export const DEFAULT_VERSION = "0.1.0";

export interface InitOptions {
  /** Project name; defaults to the directory name. */
  name?: string;
  /** Project version; defaults to `0.1.0`. */
  version?: string;
  /** Language format version; defaults to the language version the tool currently supports. */
  format?: string;
}

export interface InitFile {
  /** Path relative to the project root (`/`-separated). */
  path: string;
  content: string;
}

export interface InitTree {
  /** Directories to create (relative to the project root, `/`-separated). */
  directories: string[];
  /** Files to write. */
  files: InitFile[];
}

/** Directory name -> project name: take the basename, strip trailing slashes. */
export function projectNameFromDir(dir: string): string {
  const trimmed = dir.replace(/\/+$/, "");
  const base = trimmed.slice(trimmed.lastIndexOf("/") + 1);
  return base.length > 0 ? base : trimmed;
}

/** Contents of `project.toml`: only three required entries; add the rest as needed. */
export function renderProjectToml(options: InitOptions & { name: string }): string {
  return [
    "# TextEDA project file.",
    "# `format` is the TextEDA format version, maintained by the tool; do not edit it by hand.",
    "",
    "[project]",
    `name = ${JSON.stringify(options.name)}`,
    `version = ${JSON.stringify(options.version ?? DEFAULT_VERSION)}`,
    `format = ${JSON.stringify(options.format ?? CURRENT_FORMAT)}`,
    "",
  ].join("\n");
}

/** Contents of `docs/README.md`: getting-started notes for a new project. */
export function renderDocsReadme(name: string): string {
  return [
    `# ${name}`,
    "",
    "Empty project scaffold generated by `texteda init`.",
    "",
    "```",
    `${name}/`,
    "├── project.toml        # Project metadata (name, version, format version)",
    "├── assets/             # What this project owns",
    "│   ├── symbols/        # Symbol libraries: symbols/<lib>/<symbol_id>.teda",
    "│   ├── footprints/     # Footprint libraries: footprints/<lib>/<footprint_id>.teda",
    "│   ├── components/     # Devices: one per .teda, parts and generics alike (component_id taken from the file name)",
    "│   └── procurement/    # Procurement selections: procurement/primary/<board_id>.teda (normative)",
    "├── external/           # What this project references but does not own (simulation models; a library template is imported, not vendored)",
    "├── design/             # The circuit — the truth",
    "│   ├── sch/            # Schematic descriptions: one board per .teda, sch/<board_id>.teda",
    "│   ├── modules/        # Module descriptions: one module per .teda, modules/<module_id>.teda",
    "│   ├── pcb/            # PCB descriptions; can be added later",
    "│   └── system/         # Multi-board connection descriptions: one system per .teda",
    "├── views/              # The drawings: hand-written print pages, views/<board_id>/<page_id>.view.teda",
    "└── docs/               # Design documents, review records, simulation conclusions",
    "```",
    "",
    "Next steps:",
    "",
    "1. Write symbol and footprint descriptions in `assets/symbols/` and `assets/footprints/`, then the devices in `assets/components/`: a `kind: part` per specific device, a `kind: generic` per device class.",
    "2. Write the board `design/sch/<board_id>.teda`, referencing those ids via `instances`.",
    "3. When a physical implementation is needed, create a file with the same name under `design/pcb/`.",
    "",
    "See the repository's `spec/teda.md` for the syntax and `docs/adr/` for decision records.",
    "",
  ].join("\n");
}

/** Compute the directories and files that init will create. */
export function initTree(options: InitOptions & { name: string }): InitTree {
  return {
    directories: [
      "assets/symbols",
      "assets/footprints",
      "assets/components",
      "assets/procurement/primary",
      "assets/procurement/alternatives",
      "external/simulation",
      "design/sch",
      "design/modules",
      "design/pcb",
      "design/system",
      "views",
      "docs",
    ],
    files: [
      { path: "project.toml", content: renderProjectToml(options) },
      { path: "assets/symbols/.gitkeep", content: "" },
      { path: "assets/footprints/.gitkeep", content: "" },
      { path: "assets/components/.gitkeep", content: "" },
      { path: "assets/procurement/primary/.gitkeep", content: "" },
      { path: "assets/procurement/alternatives/.gitkeep", content: "" },
      { path: "external/simulation/.gitkeep", content: "" },
      { path: "design/sch/.gitkeep", content: "" },
      { path: "design/modules/.gitkeep", content: "" },
      { path: "design/pcb/.gitkeep", content: "" },
      { path: "design/system/.gitkeep", content: "" },
      { path: "views/.gitkeep", content: "" },
      { path: "docs/README.md", content: renderDocsReadme(options.name) },
    ],
  };
}
