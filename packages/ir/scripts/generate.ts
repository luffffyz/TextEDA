// Generates two things from schemas/ir/<version>/*.schema.json, both landing in src/generated/:
//   1. schemas.ts — the inlined schema documents (shared by Ajv and browsers; no file reads at runtime)
//   2. types/*.ts  — TS types (json-schema-to-typescript)
// Generation is idempotent: the same schemas produce byte-identical artifacts; CI catches drift with `git diff --exit-code`.
import { compile } from "json-schema-to-typescript";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { codeEntry, DIAGNOSTIC_CODES, DIAGNOSTIC_CODE_IDS, DIAGNOSTIC_DOMAINS } from "../src/diagnostics/codes.ts";
import { IR_QUANTITY_SPECS, quantityOfField } from "../src/units.ts";

const irVersion = process.env.IR_VERSION ?? "v0.7";
const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "../../../schemas/ir", irVersion);
const outDir = join(here, "../src/generated");

const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json"))
  .sort();

const common = JSON.parse(readFileSync(join(schemaDir, "common.schema.json"), "utf8"));
const commonId: string = common.$id;
const commonRef = `${commonId}#/$defs/`;

// Cross-file $refs are expressed via $id (URN), which is part of the contract; inline them into #/$defs/…
// before generating TS types, because the type generator resolves $refs by file path and does not understand URNs.
function inlineCommonRefs(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(inlineCommonRefs);
  if (node && typeof node === "object") {
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
      if (key === "$ref" && typeof value === "string" && value.startsWith(commonRef)) {
        out.$ref = value.replace(commonRef, "#/$defs/");
      } else {
        out[key] = inlineCommonRefs(value);
      }
    }
    return out;
  }
  return node;
}

const ROOT_NAMES: Record<string, string> = {
  project: "Project",
  procurement: "Procurement",
  component: "Component",
  schematic: "Schematic",
  pcb: "Pcb",
  system: "System",
  manifest: "Manifest",
  footprint: "Footprint",
  symbol: "Symbol",
  common: "Common",
};

const kinds: string[] = [];
const documents: unknown[] = [];
/** Each shard's **own** $defs (without the merged-in common); docs render only the own parts. */
const ownDefs = new Map<string, Record<string, unknown>>();
const outputs: { path: string; content: string }[] = [];

for (const file of files) {
  const kind = file.replace(".schema.json", "");
  const raw = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));

  // When a shard contains common's $defs, merge them in (names cannot clash: guaranteed by the contract side).
  // Note to use the rewritten copy: URN refs inside raw.$defs are not yet rewritten and would clobber the rewritten version.
  const rewritten = inlineCommonRefs(raw) as Record<string, unknown>;
  const merged = kind === "common" ? raw : {
    ...rewritten,
    $defs: { ...(common.$defs ?? {}), ...(rewritten.$defs ?? {}) },
  };

  // The root type name is decided by title; titles in the contract are Chinese descriptions; replace them with the
  // PascalCase of kind so generated types are called Schematic / Component / … instead of TextEDAIRV01Schematic.
  if (kind !== "common") {
    (merged as Record<string, unknown>).title = ROOT_NAMES[kind] ?? kind;
  }

  documents.push(merged);
  kinds.push(kind);
  ownDefs.set(kind, (rewritten.$defs ?? {}) as Record<string, unknown>);

  const ts = await compile(merged, kind, {
    bannerComment: "",
    additionalProperties: false,
    // Every definition in `$defs` gets a named type, even when a property adds a sibling field to `$ref`
    // (e.g. a per-use `description`), which inlines the reference. Without this flag, adding one
    // description would quietly remove names like `Slug` / `NetOrPinRef` from the type surface.
    unreachableDefinitions: true,
    style: { semi: true, singleQuote: false, printWidth: 100 },
  });
  outputs.push({
    path: join(outDir, "types", `${kind}.ts`),
    content: `// Generated by packages/ir/scripts/generate.ts from schemas/ir/${irVersion}; do not edit by hand.\n${ts}`,
  });
}

// Schema documents for the runtime: fixed order, registered by $id with Ajv.
outputs.push({
  path: join(outDir, "schemas.ts"),
  content: [
    "// Generated by packages/ir/scripts/generate.ts; do not edit by hand.",
    `// Source: schemas/ir/${irVersion}/ (${kinds.join(" · ")})`,
    `export const irVersion = ${JSON.stringify(irVersion.replace(/^v/, ""))};`,
    `export const schemaKinds = ${JSON.stringify(kinds)} as const;`,
    "export const schemas: readonly Record<string, unknown>[] = [",
    ...documents.map((d) => `  ${JSON.stringify(d)},`),
    "];",
    "",
  ].join("\n"),
});

// Error-code registry doc (ADR-0016): the registry is the single source of truth, the doc is derived.
// It lives under docs/ (not src/generated/) because it is a human-readable contract explanation.
function renderErrorCodesDoc(): string {
  const lines: string[] = [];
  lines.push("# Diagnostic Error Code Registry");
  lines.push("");
  lines.push("> Generated by `packages/ir/scripts/generate.ts` from `packages/ir/src/diagnostics/codes.ts`; do not edit by hand.");
  lines.push("> Decisions, lifecycle rules and the freezing convention are in `docs/adr/0016-diagnostic-error-codes.md`.");
  lines.push("");
  lines.push(
    `${DIAGNOSTIC_CODE_IDS.length} codes in total. The domain vocabulary is closed: ${DIAGNOSTIC_DOMAINS.map((d) => `\`${d}\``).join(" · ")}.`,
  );
  lines.push("");
  lines.push("Codes look like `domain.short-slug`. **A code is frozen once emitted**: no changing meaning, no renaming, no reuse;");
  lines.push("when semantics change, emit a new code and mark the old one `[DEPRECATED → new.code]`.");
  lines.push("");
  for (const domain of DIAGNOSTIC_DOMAINS) {
    const codes = DIAGNOSTIC_CODE_IDS.filter((code) => DIAGNOSTIC_CODES[code].domain === domain);
    lines.push(`## \`${domain}\``);
    lines.push("");
    if (codes.length === 0) {
      lines.push("(domain frozen, no codes yet — the related description types have not landed.)");
      lines.push("");
      continue;
    }
    lines.push("| Code | Severity | Meaning | How to fix | Spec |");
    lines.push("|---|---|---|---|---|");
    for (const code of codes) {
      const entry = codeEntry(code);
      lines.push(
        `| \`${code}\` | ${entry.severity} | ${entry.summary} | ${entry.hint ?? "—"} | ${entry.spec.join(", ") || "—"} |`,
      );
    }
    lines.push("");
  }
  return `${lines.join("\n")}`;
}

outputs.push({
  path: join(here, "../../../docs/error-codes.md"),
  content: renderErrorCodesDoc(),
});

// IR contract reference (for agents to look up field semantics and units): the schema is the single
// source of truth, the doc is derived.
//
// It answers only two questions: what type a field is and what its unit is. Behavioral semantics
// live in spec/ (the language-wide spec is spec/teda.md); the doc only gives pointers and never restates the spec — avoiding a
// second spec that could drift.
type SchemaNode = Record<string, unknown>;

interface FieldRow {
  /** Field name. */
  name: string;
  /** Type (rendered short form). */
  type: string;
  /** Whether it is required. */
  required: boolean;
  /** Canonical unit (quantity fields only). */
  unit: string;
  /** Description (the schema's description). */
  description: string;
}

interface ObjectBlock {
  /** Block title, e.g. `Top-level` / `constraint`. */
  title: string;
  /** Whether it is closed (additionalProperties: false). */
  closed: boolean;
  /** Field table. */
  fields: FieldRow[];
}

function isSchemaNode(value: unknown): value is SchemaNode {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Render one field node as a short type notation. */
function renderType(node: unknown): string {
  if (!isSchemaNode(node)) return "—";
  if (typeof node.$ref === "string") {
    const at = node.$ref.lastIndexOf("/");
    return at >= 0 ? node.$ref.slice(at + 1) : node.$ref;
  }
  if (node.const !== undefined) return `\`${String(node.const)}\``;
  if (Array.isArray(node.enum)) return node.enum.map((v) => `\`${String(v)}\``).join(" \\| ");
  const branches = (node.oneOf ?? node.anyOf) as unknown[] | undefined;
  if (Array.isArray(branches)) {
    const consts = branches
      .map((b) => (isSchemaNode(b) ? b.const : undefined))
      .filter((c): c is string => typeof c === "string");
    if (consts.length > 0) return `Polymorphic: ${consts.map((c) => `\`${c}\``).join(", ")}`;
    return "Polymorphic";
  }
  if (node.type === "array") return `array<${renderType(node.items)}>`;
  if (typeof node.type === "string") return node.type;
  return "—";
}

/** Find a referenced definition in the shard's $defs. */
function lookupDef(doc: SchemaNode, ref: string): SchemaNode | undefined {
  const at = ref.lastIndexOf("/");
  if (at < 0) return undefined;
  const name = ref.slice(at + 1);
  const defs = doc.$defs as Record<string, unknown> | undefined;
  const hit = defs?.[name];
  return isSchemaNode(hit) ? hit : undefined;
}

/** Description: the field's own description wins; otherwise take the referenced definition's description. */
function descriptionOf(doc: SchemaNode, node: unknown): string {
  if (!isSchemaNode(node)) return "";
  if (typeof node.description === "string") return node.description;
  if (typeof node.$ref === "string") {
    const def = lookupDef(doc, node.$ref);
    if (def && typeof def.description === "string") return def.description;
  }
  return "";
}

/** Flatten one object's properties into a field table. */
function fieldsOf(doc: SchemaNode, obj: SchemaNode): FieldRow[] {
  const props = obj.properties as Record<string, unknown> | undefined;
  if (!props) return [];
  const required = new Set((obj.required as string[] | undefined) ?? []);
  const rows: FieldRow[] = [];
  for (const name of Object.keys(props).sort()) {
    const node = props[name];
    const kind = quantityOfField(name);
    rows.push({
      name,
      type: renderType(node),
      required: required.has(name),
      unit: kind ? IR_QUANTITY_SPECS[kind].canonicalLabel : "—",
      description: descriptionOf(doc, node),
    });
  }
  return rows;
}

/**
 * The objects **inlined** in a shard: the payload itself (`component`, `footprint`, …) and the
 * objects inside it (`project.authors[]`, `manifest.shards[]`, …). They are not in `$defs`, so
 * without this the reference would list the shard's top level and stop — an agent looking for
 * "what is a device's `mpn`" would find nothing and guess.
 */
function inlinedObjects(
  node: unknown,
  prefix: string,
  out: { title: string; node: SchemaNode }[],
): void {
  if (!isSchemaNode(node)) return;
  if (node.type === "object" && isSchemaNode(node.properties)) {
    out.push({ title: prefix, node });
    for (const [name, child] of Object.entries(node.properties as Record<string, unknown>)) {
      inlinedObjects(child, `${prefix}.${name}`, out);
    }
    return;
  }
  if (node.type === "array") {
    const items = node.items;
    if (!isSchemaNode(items) || !isSchemaNode(items.properties)) return;
    out.push({ title: `${prefix}[]`, node: items });
    for (const [name, child] of Object.entries(items.properties as Record<string, unknown>)) {
      inlinedObjects(child, `${prefix}[].${name}`, out);
    }
  }
}

function renderIrReferenceDoc(): string {
  const lines: string[] = [];
  const missing: string[] = [];
  let fieldCount = 0;
  let describedCount = 0;

  const pushBlock = (kind: string, title: string, block: ObjectBlock): void => {
    lines.push(`### ${title}`);
    lines.push("");
    if (block.fields.length === 0) {
      lines.push("(no fields)");
      lines.push("");
      return;
    }
    lines.push("| Field | Type | Required | Unit | Description |");
    lines.push("|---|---|---|---|---|");
    for (const field of block.fields) {
      fieldCount += 1;
      if (field.description.length > 0) describedCount += 1;
      else missing.push(`${kind}.${title} → \`${field.name}\``);
      const description = field.description.length > 0 ? field.description : "**(missing description)**";
      lines.push(
        `| \`${field.name}\` | ${field.type} | ${field.required ? "yes" : "no"} | ${field.unit} | ${description} |`,
      );
    }
    lines.push("");
  };

  lines.push(`# IR Contract Reference (${irVersion})`);
  lines.push("");
  lines.push(
    "> Generated by `packages/ir/scripts/generate.ts` from `schemas/ir/" +
      irVersion +
      "/`; do not edit by hand.",
  );
  lines.push(">");
  lines.push(
    "> This table answers only two questions: **what type a field is** and **what its unit is**. Behavioral semantics are defined by `spec/` (the language-wide spec is `spec/teda.md`).",
  );
  lines.push(">");
  lines.push(
    "> Units are determined by field-name suffixes (ADR-0008 decision 4): `min_uv` is voltage (µV), `max_na` is current (nA), `value_mohm` is impedance (mΩ).",
  );
  lines.push("");

  for (const [index, doc] of documents.entries()) {
    if (!isSchemaNode(doc)) continue;
    const kindKey = kinds[index] ?? `kind${index}`;
    const id = typeof doc.$id === "string" ? doc.$id : kindKey;
    const summary = typeof doc.description === "string" ? doc.description : "";
    lines.push(`## \`${kindKey}\``);
    lines.push("");
    lines.push(`- schema: \`${id}\``);
    if (summary.length > 0) lines.push(`- ${summary}`);
    lines.push("");
    pushBlock(kindKey, "Top-level", {
      title: "Top-level",
      closed: doc.additionalProperties === false,
      fields: fieldsOf(doc, doc),
    });
    // The inlined objects: the payload the shard carries, and what is inlined inside it.
    const inlined: { title: string; node: SchemaNode }[] = [];
    for (const [name, node] of Object.entries((doc.properties as Record<string, unknown>) ?? {})) {
      inlinedObjects(node, name, inlined);
    }
    for (const block of inlined) {
      pushBlock(kindKey, block.title, {
        title: block.title,
        closed: block.node.additionalProperties === false,
        fields: fieldsOf(doc, block.node),
      });
    }
    const defs = ownDefs.get(kindKey) ?? {};
    for (const name of Object.keys(defs).sort()) {
      const def = defs[name];
      if (!isSchemaNode(def)) continue;
      if (def.properties) {
        pushBlock(kindKey, name, {
          title: name,
          closed: def.additionalProperties === false,
          fields: fieldsOf(doc, def),
        });
        continue;
      }
      // Union types (`oneOf` / `anyOf`): each branch is usually an object with `properties`, and the
      // quantity fields live inside the branches (`min_uv` / `max_na` …). Without expanding, no unit
      // can be found for these fields.
      const branches = (def.oneOf ?? def.anyOf) as unknown[] | undefined;
      if (!Array.isArray(branches)) continue;
      for (const branch of branches) {
        if (!isSchemaNode(branch) || !branch.properties) continue;
        const props = branch.properties;
        if (!isSchemaNode(props)) continue;
        const typeNode = props.type;
        const tag = isSchemaNode(typeNode) ? typeNode.const : undefined;
        const title = typeof tag === "string" ? `${name} (type=${tag})` : name;
        pushBlock(kindKey, title, {
          title,
          closed: branch.additionalProperties === false,
          fields: fieldsOf(doc, branch),
        });
      }
    }
  }

  lines.push("## Field-description coverage");
  lines.push("");
  const percent = fieldCount === 0 ? 0 : Math.round((describedCount * 100) / fieldCount);
  lines.push(
    `${describedCount}/${fieldCount} fields described (${percent}%). Fields without a description have no citable semantics; agents can only guess when reading them.`,
  );
  lines.push("");
  if (missing.length > 0) {
    lines.push("| Location | Field |");
    lines.push("|---|---|");
    for (const item of missing) {
      const at = item.lastIndexOf("→ ");
      lines.push(`| ${item.slice(0, at)} | ${item.slice(at + 2)} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

outputs.push({
  path: join(here, "../../../docs/ir-reference.md"),
  content: renderIrReferenceDoc(),
});

// --check: compare only, never write. CI uses it to block "changed the schema but forgot to regenerate".
const check = process.argv.includes("--check");
const drifted: string[] = [];
for (const { path, content } of outputs) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) {
    drifted.push(path);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (check) {
  if (drifted.length > 0) {
    console.error("generated artifacts are out of sync with the schemas; run `bun run gen`:");
    for (const path of drifted) console.error(`  ${path}`);
    process.exit(1);
  }
  console.log(`generated artifacts up to date (${outputs.length} files)`);
} else {
  console.log(`generated ${kinds.length} schemas + types into ${outDir}`);
}
